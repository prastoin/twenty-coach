// Emits the generated core client into packages/shared so out-of-app
// consumers (the trainee PWA today) get typed queries and mutations without
// depending on twenty-client-sdk or a live instance — the published SDK
// ships `type CoreSchema = {}`, and the real client is generated into
// node_modules, which is gitignored and only exists after `twenty apply`.
//
// TypeScript source only: the compiled .mjs/.cjs bundles produce huge
// esbuild-version-dependent diffs and the consumer compiles the source
// anyway. Superseded once `twenty dev:generate-client --output` ships
// (twentyhq/core-team-issues#2752).
//
// In-app code (logic functions, front components) must keep importing
// `twenty-client-sdk/core`: the server swaps in a client generated from the
// installing instance, whereas this one bakes the dev workspace's typeMap.
//
// Usage: yarn api:client [--check]   (run `yarn twenty -r <remote> apply` first)
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { generateCoreClientFromSchema } from 'twenty-client-sdk/generate';

const here = dirname(fileURLToPath(import.meta.url));
const SDL_PATH = join(
  here,
  '../node_modules/twenty-client-sdk/dist/core/generated/schema.graphql',
);
const TARGET_DIR = join(here, '../../shared/src/generated/client');
const HEADER = `// @generated by \`yarn api:client\` — do not edit by hand.
// Source: the workspace GraphQL schema, after \`yarn twenty apply\`.\n`;

const isSource = (name) => name.endsWith('.ts') || name.endsWith('.tsx');

const collect = async (dir, base = dir) => {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collect(path, base)));
    } else if (isSource(entry.name)) {
      files.push([relative(base, path), HEADER + (await readFile(path, 'utf8'))]);
    }
  }
  return files.sort(([a], [b]) => a.localeCompare(b));
};

const schema = await readFile(SDL_PATH, 'utf8').catch(() => {
  console.error(
    `No generated schema at ${SDL_PATH}.\nRun \`yarn twenty -r <remote> apply\` against a running instance first.`,
  );
  process.exit(1);
});

const scratch = await mkdtemp(join(tmpdir(), 'coach-client-'));
// Emit the genql client only. The default wrapper is the app-context
// `CoreApiClient`, which reads `process.env` at module scope and so throws
// on import in a browser — and is useless here anyway, since the PWA
// authenticates with the trainee's OAuth token rather than an app token.
await generateCoreClientFromSchema({
  schema,
  outputPath: scratch,
  clientWrapperTemplateSource: '',
});
const emitted = await collect(scratch);
await rm(scratch, { recursive: true, force: true });

if (process.argv.includes('--check')) {
  for (const [name, content] of emitted) {
    if ((await readFile(join(TARGET_DIR, name), 'utf8').catch(() => '')) !== content) {
      console.error(
        `${name} is stale — run \`yarn api:client\` and commit the result.`,
      );
      process.exit(1);
    }
  }
  console.log('Generated client is up to date.');
} else {
  await rm(TARGET_DIR, { recursive: true, force: true });
  for (const [name, content] of emitted) {
    const path = join(TARGET_DIR, name);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
  console.log(`Wrote ${emitted.length} files to ${TARGET_DIR}`);
}
