// Emits the workspace GraphQL types into packages/shared so every package
// can use them without depending on twenty-client-sdk or a live instance
// (the published SDK ships `type CoreSchema = {}`; the real types are
// generated into node_modules, which is gitignored and server-dependent).
// Upstream proposal for a native `--output`: twentyhq/core-team-issues#2752.
//
// Usage: yarn schema:types [--check]   (run `yarn twenty apply` first)
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { generateCoreClientFromSchema } from 'twenty-client-sdk/generate';

const here = dirname(fileURLToPath(import.meta.url));
const SDL_PATH = join(
  here,
  '../node_modules/twenty-client-sdk/dist/core/generated/schema.graphql',
);
const TARGET = join(here, '../../shared/src/generated/schema.ts');
const ENUMS_TARGET = join(here, '../../shared/src/generated/enums.ts');
const HEADER = `// @generated by \`yarn schema:types\` — do not edit by hand.
// Source: the workspace GraphQL schema, after \`yarn twenty apply\`.\n`;

// The schema types are erased at runtime, so SELECT values are also emitted
// as a value → label map: the same metadata, usable for parsing and display.
const emitEnums = (sdl) => {
  const entries = [...sdl.matchAll(/enum (\w+) \{([^}]*)\}/g)].map(
    ([, name, body]) => {
      const members = [
        ...body.matchAll(/(?:"""(.*?)"""\s*)?^\s*([A-Za-z][A-Za-z0-9_]*)\s*$/gms),
      ].map(([, label, value]) => `    ${value}: ${JSON.stringify(label ?? value)},`);
      return `  ${name}: {\n${members.join('\n')}\n  },`;
    },
  );
  return `${HEADER}\nexport const SCHEMA_ENUMS = {\n${entries.join('\n')}\n} as const;\n`;
};

const schema = await readFile(SDL_PATH, 'utf8').catch(() => {
  console.error(
    `No generated schema at ${SDL_PATH}.\nRun \`yarn twenty -r <remote> apply\` against a running instance first.`,
  );
  process.exit(1);
});

const scratch = await mkdtemp(join(tmpdir(), 'coach-schema-'));
await generateCoreClientFromSchema({ schema, outputPath: scratch });
const emitted = HEADER + (await readFile(join(scratch, 'schema.ts'), 'utf8'));
await rm(scratch, { recursive: true, force: true });

const outputs = [
  [TARGET, emitted],
  [ENUMS_TARGET, emitEnums(schema)],
];

if (process.argv.includes('--check')) {
  for (const [path, content] of outputs) {
    if ((await readFile(path, 'utf8').catch(() => '')) !== content) {
      console.error(
        `${path} is stale — run \`yarn schema:types\` and commit the result.`,
      );
      process.exit(1);
    }
  }
  console.log('Schema types are up to date.');
} else {
  await mkdir(dirname(TARGET), { recursive: true });
  for (const [path, content] of outputs) {
    await writeFile(path, content);
    console.log(`Wrote ${path}`);
  }
}
